"""Write v3/design/pin_budget.md: the nRF52832-CIAA (WLCSP-50) GPIO assignment of V3-F, generated from src/mcu_rf.py (GPIO / SPARE), the pin
map pinmap/C509405.yaml and the built netlists (both variants must agree). The QFN-48 fallback of V2-B is not built for V3-F.
usage: python pin_budget.py
"""
import json, os, re, sys, yaml
HERE = os.path.dirname(os.path.abspath(__file__)); DESIGN = os.path.dirname(HERE)
P = {v: json.load(open(os.path.join(DESIGN, "out", v, "parts.json"))) for v in ("v3f", "v3f_fldnp")}
wl = yaml.safe_load(open(os.path.join(DESIGN, "pinmap", "C509405.yaml")))["pins"]
V2 = json.load(open(os.path.join(DESIGN, "v2_ref", "netlist", "parts_dock_wlcsp.json")))["U6"]["pins"]
def port(name):
    m = re.search(r"P0\.(\d\d)", name); return f"P0.{m.group(1)}" if m else None
ball = {port(p["name"]): b for b, p in wl.items() if port(p["name"])}
NEAR = {f"P0.{i}" for i in range(22, 32)}          # PS v1.4 Tables 5 and 6 (p.17): low drive, low frequency I/O only
def ring(b):
    r, c = b[0], int(b[1:])
    return "outer" if r in "AH" or c in (1, 7) or b in ("B2", "C2") else "inner (via-in-pad)"
WHY = {
 "ECG_PWDN": "ADS1291 PWDN/RESET, 10 k pull-down R311", "ECG_DRDY": "ADS1291 DRDY, 500 Hz edge interrupt: not a near-radio pin",
 "SPI_SCK": "SPIM clock: ADS1291, MAX86141, MX25R and (through U17) the display", "SPI_MOSI": "SPIM data out (also the display SI through U17)",
 "SPI_MISO": "SPIM data in (shared, tri-state slaves)", "CS_ECG": "ADS1291 CS, pull-up R315", "CS_PPG": "MAX86141 CSB, pull-up R402",
 "CS_FLASH": "MX25R CS#, pull-up R501", "PPG_INT": "MAX86141 open-drain INT, pull-up R401", "I2C_SDA": "TWIM 400 kHz (INA236 x2, LIS2DW12, TMP117), pull-up R505",
 "I2C_SCL": "TWIM clock, pull-up R506", "IMU_INT1": "LIS2DW12 INT1: wake, raise, tap and the FIFO threshold (CTRL4 INT1_FTH)",
 "NTC_ADC": "SAADC AIN4: pack NTC through R149 1 M (C113 at the pin)", "NTC_EN": "MCU bias of the O-2 ladder through D19B for its own NTC reading (static, short pulses)",
 "PV_INH": "Q1 gate: harvest inhibit / Isc probe / firmware 0-45 C governor (static, 10 M pull-down R108)", "ECG_PWR_EN": "U3 enable through R123 (Q9 overrides while VBUS)",
 "PWR_HOLD": "keeps BQ25570 EN low through D9 / Q4 (G-4)", "PWR_CYC": "hard power-cycle one-shot through D11 (G-4)",
 "INA_EN": "INA236 rail switch U13 (10 M pull-down R131)", "ALERT_LED": "skin-hot warning LED switch Q6 (1 M pull-down R508); freed if the LED chain goes",
 "MOTOR_PWM": "[V3F] Q12 gate through R162: ERM PWM 20-40 kHz; was ECG_START (START held low by R316, ADS1291 p.44, p.48)",
 "CHG_DIS": "[V3F] Q10 gate: BQ25170 TS low (charge off, 41 C skin); NFC pad: UICR NFCPINS = GPIO", "FL_EN": "[V3F] Q11 gate: front-light PWM; NFC pad: UICR NFCPINS = GPIO",
 "EXTCOMIN": "[V3F] panel COM inversion 60 Hz from RTC -> PPI -> GPIOTE, through U17", "DISP_CTRL": "[V3F] panel DISP through U21 (was the debug UART_TX: logs go over SWD / RTT)",
 "DISP_EN": "[V3F] U16 EN + U17 / U21 VCCA and OE (display power domain)", "CHG_PG_N": "[V3F] BQ25170 /PG (open drain, 220 k pull-up R143): head attached; SENSE wakes System OFF",
 "BTN_N": "[V3F] side button through Q13, active low, SENSE wakes System OFF (was IMU_INT2)", "DISP_SCS": "[V3F] panel SCS (active high) through U17",
}
u = {v: P[v]["U6"] for v in P}
L = ["# nRF52832 pin budget - SolarBand V3-F\n",
     "Generated by `tools/pin_budget.py` from `src/mcu_rf.py` and the built netlists (v3f and v3f_fldnp agree). nRF52832-CIAA WLCSP-50 only. "
     "P0.22-P0.31 are 'low drive, low frequency I/O only' (PS v1.4 Tables 5 and 6, p.17): only static or slow signals are on them.\n",
     "WLCSP ring: 'outer' balls are reached on the top layer; 'inner' balls need a via-in-pad (JLC 6-layer: via 0.15 / 0.25 mm, POFV). Escaping the inner balls "
     "is a pass item of V3-G1 (BASELINE 18).\n",
     "| GPIO | Signal V3-F | Signal V2-B dock_wlcsp | WLCSP ball | Ring | Near radio | Why |", "|---|---|---|---|---|---|---|"]
ports = sorted(ball, key=lambda p: int(p[3:]))
cnt = {"outer": 0, "inner (via-in-pad)": 0}; changed = []
for p in ports:
    b = ball[p]
    s3 = u["v3f"]["pins"].get(b) or "-"; s3d = u["v3f_fldnp"]["pins"].get(b) or "-"
    assert s3 == s3d, (p, s3, s3d)
    s2 = V2.get(b) or "-"
    if s3 != "-": cnt[ring(b)] += 1
    if s3 != s2: changed.append(f"{p} {s2} -> {s3}")
    L.append(f"| {p} | {s3} | {s2 if s2 != s3 else '='} | {b} | {ring(b)} | {'yes' if p in NEAR else ''} | {WHY.get(s3, 'spare (not connected)' if s3 == '-' else '')} |")
L.append(f"\nV3-F: {cnt['outer']} GPIO signals on outer balls, {cnt['inner (via-in-pad)']} on inner balls. Fixed-function inner balls: DCC (B6), VSS (C4, C5, E3, F5), VSS_PA (D2), N.C. (C3).")
sp = [p for p in ports if (u["v3f"]["pins"].get(ball[p]) or "-") == "-"]
L.append(f"\nSpare GPIO: {', '.join(sp) if sp else 'none'} (BASELINE 6: no pin is left; P0.24 becomes free if the LED chain goes).")
L.append("\nChanges against V2-B dock_wlcsp: " + "; ".join(changed) + ".")
L.append("\nInner balls with new V3-F signals (via-in-pad escapes for V3-G1): " +
         ", ".join(f"{p} ({ball[p]})" for p in ports if ring(ball[p]) != "outer" and (u['v3f']['pins'].get(ball[p]) or '-') != (V2.get(ball[p]) or '-')) + ".")
open(os.path.join(DESIGN, "pin_budget.md"), "w").write("\n".join(L) + "\n")
print("pin_budget.md:", cnt, "changed:", len(changed))
