"""Write design/pinmap/<LCSC>.yaml from the datasheet pin tables in pinmap_data.py (format: research/cpl-placement-gate.md
section 6.2, extended with pin type/function and package data). These files feed the SKiDL symbols (pin names exactly as
in the datasheet) and, later, cplgate G3 (pin identity).
usage: python write_pinmaps.py
"""
import os, sys, hashlib, datetime, yaml
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from pinmap_data_v3 import PARTS          # V3-F: v1 + v2 + v3 tables
OUT = os.path.join(os.path.dirname(HERE), "pinmap"); os.makedirs(OUT, exist_ok=True)

def sha(name, d, recorded=None):
    """hash of the cached PDF if the project cache still holds it; V3-F datasheets are not kept (lane rule) -> the recorded hash"""
    if d:
        p = os.path.join(d, name + ".pdf")
        if os.path.exists(p): return hashlib.sha256(open(p, "rb").read()).hexdigest()
    return recorded

class Q(str): pass
yaml.add_representer(Q, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="'"))

for c, d in PARTS.items():
    pins = {}
    for n, (name, typ, fn) in d["pins"].items():
        pins[Q(str(n))] = {"name": Q(name), "type": typ, "function": fn}
    polar = d.get("polarity")
    two_term_polar = polar and polar.get("kind") in ("diode", "led", "photodiode")
    doc = {
        "lcsc": c, "mpn": d["mpn"], "manufacturer": d["mfr"], "refs": d["refs"],
        "datasheet": {"file": (os.path.relpath(os.path.join(d["ds_dir"], d["ds"] + ".pdf"), "/path/to/SolarVest_work/wristband") if d.get("ds_dir") else "not kept in the project (read 2026-11-13, V3-F lane)"),
                      "url": d["url"], "sha256": sha(d["ds"], d.get("ds_dir"), d.get("sha256")), "doc": d["doc"],
                      "pin_table": d["pin_table"], "package_drawing_page": d.get("package_page"), "land_pattern_page": d.get("land_page")},
        "package": d["package"],
        "pin1_marker": d["pin1"],
        "polarity": polar if polar else "none",
        "pins": pins,
        "id_registers": d.get("ids"),
        "notes": d.get("notes"),
        "reviewed": {"by": "agent (datasheet transcription, re-checked against extracted text and rendered drawings)",
                     "date": datetime.date.today().isoformat(),
                     "human_review_required": bool(two_term_polar or d.get("human_review")),
                     "note": ("polarized 2-terminal part: cplgate G3 requires 'reviewed: human' before an order" if two_term_polar
                              else (f"human review required before an order: {d['human_review']}" if d.get("human_review")
                                    else "datasheet-verified; EasyEDA symbol comparison in footprint_audit.md"))},
    }
    with open(os.path.join(OUT, f"{c}.yaml"), "w") as f:
        f.write(f"# {d['mpn']} ({d['mfr']}) - datasheet pin map for {d['refs']}. Generated by v3/design/tools/write_pinmaps.py from pinmap_data*.py.\n")
        yaml.dump(doc, f, sort_keys=False, allow_unicode=True, width=140)
print(len(PARTS), "pin maps written to", OUT)
