"""Mechanical change list V2-B dock_wlcsp -> V3-F (both variants): refs removed / added / changed (value, C-number, footprint, DNP, pin nets) and
nets removed / added, from the frozen V2 netlist parts (v2_ref/netlist/parts_dock_wlcsp.json and _p0201) and the built V3-F parts (out/<v>/parts.json).
The reasons for each change are in CHANGES_V3F.md; this list is the completeness check behind it.
usage: python diff_v2.py      -> writes design/diff_v2.md and design/diff_v2.json
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); DESIGN = os.path.dirname(HERE)
V2 = {k: json.load(open(os.path.join(DESIGN, "v2_ref", "netlist", f"parts_{k}.json"))) for k in ("dock_wlcsp", "dock_wlcsp_p0201")}
V3 = {v: json.load(open(os.path.join(DESIGN, "out", v, "parts.json"))) for v in ("v3f", "v3f_fldnp")}

def nets(P):
    out = {}
    for r, p in P.items():
        for pin, n in p["pins"].items():
            if n: out.setdefault(n, set()).add(f"{r}.{pin}")
    return out
def key(r):
    a = r.rstrip("0123456789"); d = r[len(a):]
    return (a, int(d) if d else 0)
def diff(old, new):
    rem = sorted(set(old) - set(new), key=key); add = sorted(set(new) - set(old), key=key); chg = []
    for r in sorted(set(old) & set(new), key=key):
        o, n = old[r], new[r]; c = {}
        for f in ("value", "lcsc", "footprint", "dnp"):
            if o.get(f) != n.get(f): c[f] = (o.get(f), n.get(f))
        pins = {p: (o["pins"].get(p), n["pins"].get(p)) for p in set(o["pins"]) | set(n["pins"]) if o["pins"].get(p) != n["pins"].get(p)}
        if pins: c["pins"] = dict(sorted(pins.items()))
        if c: chg.append((r, c))
    no, nn = nets(old), nets(new)
    renamed = {a: b for a in set(no) - set(nn) for b in set(nn) - set(no) if no[a] == nn[b]}
    return dict(removed=[(r, old[r]["value"], old[r].get("lcsc")) for r in rem], added=[(r, new[r]["value"], new[r].get("lcsc"), new[r]["block"]) for r in add],
                changed=chg, nets_removed=sorted(set(no) - set(nn) - set(renamed)), nets_added=sorted(set(nn) - set(no) - set(renamed.values())),
                nets_renamed=renamed)
D = {"v3f vs dock_wlcsp": diff(V2["dock_wlcsp"], V3["v3f"]), "v3f vs dock_wlcsp_p0201": diff(V2["dock_wlcsp_p0201"], V3["v3f"]),
     "v3f_fldnp vs v3f": diff(V3["v3f"], V3["v3f_fldnp"])}
json.dump(D, open(os.path.join(DESIGN, "diff_v2.json"), "w"), indent=1, default=list)

def is_0201(c): return set(c) <= {"value", "lcsc", "footprint"} and "0201" in str(c.get("footprint", ("", ""))[1]) and "0402" in str(c.get("footprint", ("", ""))[0])
L = ["# V2-B dock_wlcsp -> V3-F: mechanical change list\n",
     "Generated by `tools/diff_v2.py` from `v2_ref/netlist/parts_dock_wlcsp*.json` (V2-B as frozen) and `out/<variant>/parts.json` (V3-F as built). "
     "Reasons, sources and what each change invalidates: CHANGES_V3F.md.\n"]
for title, d in D.items():
    L.append(f"## {title}\n")
    L.append(f"Removed {len(d['removed'])}, added {len(d['added'])}, changed {len(d['changed'])}; nets removed {len(d['nets_removed'])}, "
             f"added {len(d['nets_added'])}, renamed {len(d['nets_renamed'])}.\n")
    if d["removed"]: L.append("Removed: " + "; ".join(f"{r} ({v}, {c})" for r, v, c in d["removed"]) + ".\n")
    if d["added"]: L.append("Added: " + "; ".join(f"{r} ({v}, {c}, {b})" for r, v, c, b in d["added"]) + ".\n")
    only0201 = [r for r, c in d["changed"] if is_0201(c)]
    if only0201: L.append("Package 0402 -> 0201 only (same value): " + ", ".join(only0201) + ".\n")
    rows = [(r, c) for r, c in d["changed"] if not is_0201(c)]
    if rows:
        L += ["| Ref | Value / C-number / footprint / DNP | Pin nets (pin: old -> new) |", "|---|---|---|"]
        for r, c in rows:
            a = "; ".join(f"{k}: {c[k][0]} -> {c[k][1]}" for k in c if k != "pins")
            b = "; ".join(f"{p}: {o} -> {n}" for p, (o, n) in c.get("pins", {}).items())
            L.append(f"| {r} | {a.replace('|', '/')} | {b} |")
        L.append("")
    if d["nets_renamed"]: L.append("Nets renamed (same pins): " + ", ".join(f"{a} -> {b}" for a, b in sorted(d["nets_renamed"].items())) + ".\n")
    if d["nets_removed"]: L.append("Nets removed: " + ", ".join(d["nets_removed"]) + ".\n")
    if d["nets_added"]: L.append("Nets added: " + ", ".join(d["nets_added"]) + ".\n")
open(os.path.join(DESIGN, "diff_v2.md"), "w").write("\n".join(L) + "\n")
d = D["v3f vs dock_wlcsp"]
print(f"diff_v2: v3f vs dock_wlcsp: -{len(d['removed'])} +{len(d['added'])} ~{len(d['changed'])}; nets -{len(d['nets_removed'])} +{len(d['nets_added'])}; "
      f"fldnp vs v3f: ~{len(D['v3f_fldnp vs v3f']['changed'])}")
